#!/usr/bin/env python3
"""render.py -- renders generated surface files from templates per generate/targets.yaml.

Targets are declared in targets.yaml. Each render is a verbatim byte-copy of its
source template, so a dry run reproduces generated instructions and navigation
byte-identically. Once generation owns a target, it is never hand-edited.

Usage:
  python3 generate/render.py --dry-run --out-dir DIR   render all targets into DIR, touch nothing else
  python3 generate/render.py --check                   verify rendered targets and their generated checksum manifest
  python3 generate/render.py                           render targets in place and refresh generate/checksums.txt

YAML parsing uses PyYAML when available and otherwise falls back to a minimal scanner
sufficient for the flat list-of-string-mappings shape targets.yaml is constrained to,
keeping the script dependency-free (same pattern as tools/frontmatter-lint.py).
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGETS_FILE = REPO_ROOT / "generate" / "targets.yaml"
CHECKSUMS_FILE = REPO_ROOT / "generate" / "checksums.txt"
CHECKSUMS_BANNER = "# GENERATED by generate/render.py. Regenerate; do not hand-edit."

try:
    import yaml  # type: ignore

    _HAVE_YAML = True
except ImportError:
    _HAVE_YAML = False


def _fallback_parse_targets(text: str) -> list[dict[str, str]]:
    """Minimal parser for targets.yaml's constrained shape.

    Handles exactly: a top-level `targets:` key whose value is a list of flat
    mappings with scalar string values. Comments and blank lines are ignored.
    """
    targets: list[dict[str, str]] = []
    in_targets = False
    current: dict[str, str] | None = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        if not line.startswith(" "):
            in_targets = line.strip() == "targets:"
            continue
        if not in_targets:
            continue
        stripped = line.strip()
        if stripped.startswith("- "):
            current = {}
            targets.append(current)
            stripped = stripped[2:]
        if current is None or ":" not in stripped:
            continue
        key, _, value = stripped.partition(":")
        current[key.strip()] = value.strip()
    return targets


def load_targets() -> list[dict[str, str]]:
    text = TARGETS_FILE.read_text(encoding="utf-8")
    if _HAVE_YAML:
        data = yaml.safe_load(text)
        targets = data.get("targets", []) if isinstance(data, dict) else []
    else:
        targets = _fallback_parse_targets(text)
    for t in targets:
        for field in ("name", "template", "output"):
            if not t.get(field):
                sys.exit(f"render.py: target missing required field '{field}': {t}")
    return targets


def render_target(target: dict[str, str]) -> bytes:
    """Render a declared target as a verbatim byte-copy of its source template."""
    return (REPO_ROOT / target["template"]).read_bytes()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="render into --out-dir instead of in place")
    parser.add_argument("--out-dir", type=Path, help="destination directory for --dry-run output")
    parser.add_argument("--check", action="store_true", help="verify on-disk targets match a fresh render")
    args = parser.parse_args()

    if args.dry_run and not args.out_dir:
        parser.error("--dry-run requires --out-dir")

    targets = load_targets()
    checksum_lines: list[str] = []
    drift = False

    for target in targets:
        rendered = render_target(target)
        digest = sha256(rendered)
        out_rel = target["output"]
        checksum_lines.append(f"{digest}  {out_rel}")

        if args.check:
            on_disk = REPO_ROOT / out_rel
            if not on_disk.exists() or sha256(on_disk.read_bytes()) != digest:
                print(f"DRIFT {out_rel} (rendered {digest})")
                drift = True
            else:
                print(f"OK    {out_rel} {digest}")
            continue

        if args.dry_run:
            dest = args.out_dir / out_rel
        else:
            dest = REPO_ROOT / out_rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(rendered)
        print(f"WROTE {dest} {digest}")

    checksum_text = "\n".join([CHECKSUMS_BANNER, *checksum_lines]) + "\n"
    if args.check:
        if not CHECKSUMS_FILE.exists() or CHECKSUMS_FILE.read_bytes() != checksum_text.encode("utf-8"):
            print("DRIFT generate/checksums.txt (regenerate with generate/render.py)")
            drift = True
        else:
            print("OK    generate/checksums.txt")
        return 1 if drift else 0

    if not args.dry_run:
        CHECKSUMS_FILE.write_text(checksum_text, encoding="utf-8")
        print(f"WROTE {CHECKSUMS_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
